function getRandomItem(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

const generatedPhrases = new Set();
function generateUniqueLongMessage() {
  let phrase = "";
  while (true) {
    phrase = `${getRandomItem(prefixes)} ${getRandomItem(middles)}. ${getRandomItem(extensions)} ${getRandomItem(suffixes)}`;
    if (!generatedPhrases.has(phrase)) {
      generatedPhrases.add(phrase);
      return phrase;
    }
  }
}

